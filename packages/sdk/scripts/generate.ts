/*
 * Generates src/generated.ts from the API contract: one input and one
 * output type per operation, and the table the client calls them through.
 * `pnpm generate` writes it (through test/generated.test.ts, which fails
 * when it is stale).
 */
import { type OperationDef, pathParams, registry } from "@fyrden/api-contract";
import { z } from "zod";

type Schema = Record<string, unknown>;

/** `repos.collaborators.set` → `ReposCollaboratorsSet`. */
function typeName(id: string): string {
  return id
    .split(/[._]/)
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join("");
}

const IDENT = /^[A-Za-z_$][A-Za-z0-9_$]*$/;

/** Text safe inside a doc comment. */
const comment = (text: string) => text.replace(/\*\//g, "* /");

/** A TypeScript type for a JSON Schema (the subset zod writes). */
function tsType(schema: Schema, indent: string): string {
  if (schema.const !== undefined) return JSON.stringify(schema.const);
  if (Array.isArray(schema.enum)) return schema.enum.map((v) => JSON.stringify(v)).join(" | ");
  const union = (schema.anyOf ?? schema.oneOf) as Schema[] | undefined;
  if (union) return union.map((s) => tsType(s, indent)).join(" | ");
  const type = schema.type;
  if (Array.isArray(type))
    return type.map((t) => tsType({ ...schema, type: t }, indent)).join(" | ");
  switch (type) {
    case "string":
      return "string";
    case "number":
    case "integer":
      return "number";
    case "boolean":
      return "boolean";
    case "null":
      return "null";
    case "array": {
      const items = schema.items as Schema | undefined;
      const inner = items ? tsType(items, indent) : "unknown";
      return /[|&]/.test(inner) ? `(${inner})[]` : `${inner}[]`;
    }
    case "object": {
      const properties = (schema.properties ?? {}) as Record<string, Schema>;
      const required = new Set((schema.required as string[] | undefined) ?? []);
      const entries = Object.entries(properties);
      const extra = schema.additionalProperties;
      if (entries.length > 0 && extra && typeof extra === "object")
        throw new Error("objects with both properties and additional properties are not generated");
      if (entries.length === 0)
        return schema.additionalProperties && typeof schema.additionalProperties === "object"
          ? `Record<string, ${tsType(schema.additionalProperties as Schema, indent)}>`
          : "Record<string, never>";
      const inner = `${indent}  `;
      const lines = entries.map(([name, value]) => {
        const doc =
          typeof value.description === "string"
            ? `${inner}/** ${comment(value.description)} */\n`
            : "";
        const key = IDENT.test(name) ? name : JSON.stringify(name);
        return `${doc}${inner}${key}${required.has(name) ? "" : "?"}: ${tsType(value, inner)};`;
      });
      return `{\n${lines.join("\n")}\n${indent}}`;
    }
    default:
      return "unknown";
  }
}

function jsonSchema(schema: z.ZodType, io: "input" | "output"): Schema {
  return z.toJSONSchema(schema, { io, unrepresentable: "throw" }) as Schema;
}

/**
 * The array property a paginated output carries beside `next_cursor`, if
 * it is one: in the output itself, or in one variant of a union (a
 * directory among a path's contents).
 */
function pageItems(op: OperationDef): string | undefined {
  const input = jsonSchema(op.input, "input");
  const inProps = (input.properties ?? {}) as Record<string, Schema>;
  if (!("cursor" in inProps)) return undefined;
  const output = jsonSchema(op.output, "output");
  const variants = ((output.anyOf ?? output.oneOf) as Schema[] | undefined) ?? [output];
  const fields = new Set<string>();
  for (const variant of variants) {
    const props = (variant.properties ?? {}) as Record<string, Schema>;
    if (!("next_cursor" in props)) continue;
    const arrays = Object.entries(props).filter(([, s]) => s.type === "array");
    if (arrays.length === 1) fields.add((arrays[0] as [string, Schema])[0]);
  }
  return fields.size === 1 ? [...fields][0] : undefined;
}

export function generate(): string {
  const out: string[] = [
    "// Generated by scripts/generate.ts from the API contract. Do not edit; run `pnpm generate`.",
    "",
  ];
  const table: string[] = [];
  const map: string[] = [];
  for (const op of registry) {
    const name = typeName(op.id);
    const description = op.description ?? op.summary;
    out.push(`/** Input of \`${op.id}\`: ${comment(op.summary)}. */`);
    out.push(`export type ${name}Input = ${tsType(jsonSchema(op.input, "input"), "")};`);
    out.push("");
    out.push(`/** Output of \`${op.id}\`. */`);
    out.push(`export type ${name}Output = ${tsType(jsonSchema(op.output, "output"), "")};`);
    out.push("");
    const items = pageItems(op);
    table.push(
      `  ${JSON.stringify(op.id)}: { method: ${JSON.stringify(op.method)}, path: ${JSON.stringify(op.path)}, pathParams: ${JSON.stringify(pathParams(op.path))}, idempotent: ${op.idempotency === "key"}${items ? `, items: ${JSON.stringify(items)}` : ""} },`,
    );
    map.push(
      `  /** ${comment(op.summary)}. ${description === op.summary ? "" : comment(description)} */\n  ${JSON.stringify(op.id)}: { input: ${name}Input; output: ${name}Output };`,
    );
  }
  out.push("/** How each operation is sent. */");
  out.push("export const OPERATIONS = {");
  out.push(...table);
  out.push("} as const;");
  out.push("");
  out.push("/** Each operation's input and output. */");
  out.push("export interface Operations {");
  out.push(...map);
  out.push("}");
  out.push("");
  return out.join("\n");
}
