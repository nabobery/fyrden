/** A disturbance vector: the message difference of one known SHA-1 attack family. */
export interface DisturbanceVector {
  /** Type I or II in Stevens' notation (1 or 2): DV I(K,B) or II(K,B). */
  readonly type: 1 | 2;
  readonly k: number;
  readonly b: number;
  /** The step whose saved state the recompression starts from (`testt`). */
  readonly testt: 58 | 65;
  /** This vector's bit in the mask `ubcCheck` returns (`maskb`). */
  readonly maskb: number;
  /** The expanded message-block XOR difference (`dm`), 80 words. */
  readonly dm: Uint32Array;
}

function dv(
  type: 1 | 2,
  k: number,
  b: number,
  testt: 58 | 65,
  maskb: number,
  dm: number[],
): DisturbanceVector {
  return { type, k, b, testt, maskb, dm: Uint32Array.from(dm) };
}

