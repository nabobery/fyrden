/**
 * The language a rendered code block's fence named, when it is one
 * highlighted; else null. Micromark writes the whole label as one class,
 * `language-<label>`: only a class that is exactly that, with a label the
 * list holds, counts (a label holding a space or a `language-` of its own
 * is no language). Labels are matched ignoring case, as the highlighter
 * matches them.
 */
export function fenceLanguage(className: string): string | null {
  const label = /^language-(\S+)$/.exec(className)?.[1]?.toLowerCase();
  return label !== undefined && HIGHLIGHT_LANGUAGES.has(label) ? label : null;
}

/** Code a page highlights at most: what is past it stays plain (the browser's work bounded). */
export const HIGHLIGHT_BUDGET = { bytes: 64 * 1024, blocks: 200 } as const;

/**
 * Whether a block of `size` UTF-8 bytes fits beside `spent`, what the page
 * shows highlighted now: blocks are taken in order; one larger than what is
 * left stays plain, and later smaller ones may still fit.
 */
export function fits(
  spent: { readonly bytes: number; readonly blocks: number },
  size: number,
): boolean {
  return spent.blocks < HIGHLIGHT_BUDGET.blocks && spent.bytes + size <= HIGHLIGHT_BUDGET.bytes;
}
