import { type FeatureArea, WORKFLOW_FEATURES, type WorkflowFeature } from "@fyrden/domain/ci";
import {
  ACTION_PINS,
  CASES,
  type CorpusCase,
  ELSEWHERE,
  type ElsewhereProof,
  IMAGE_PINS,
  rowKey,
} from "@fyrden/testing/ci-corpus";
import { RUNNER_SHA256 } from "../runner/binary.ts";

export interface CompatibilityInput {
  readonly features: readonly WorkflowFeature[];
  readonly cases: readonly CorpusCase[];
  readonly elsewhere: readonly ElsewhereProof[];
  readonly runnerVersions: readonly string[];
  readonly actionPins: readonly {
    readonly action: string;
    readonly tag: string;
    readonly commit: string;
  }[];
  readonly images: Readonly<Record<string, string>>;
}

export const DEFAULT_INPUT: CompatibilityInput = {
  features: WORKFLOW_FEATURES as readonly WorkflowFeature[],
  cases: CASES,
  elsewhere: ELSEWHERE,
  runnerVersions: Object.keys(RUNNER_SHA256),
  actionPins: ACTION_PINS,
  images: IMAGE_PINS,
};

const NIGHTLY = "https://github.com/nabobery/fyrden/actions/workflows/nightly.yml";
const SAME_REPOSITORY_ACTION =
  "https://docs.github.com/en/actions/how-tos/write-workflows/choose-what-workflows-do/find-and-customize-actions#adding-an-action-from-the-same-repository";

const AREAS: readonly { readonly area: FeatureArea; readonly title: string }[] = [
  { area: "yaml", title: "YAML" },
  { area: "workflow", title: "Workflow" },
  { area: "trigger", title: "Triggers" },
  { area: "job", title: "Jobs" },
  { area: "step", title: "Steps" },
  { area: "expression", title: "Expressions" },
];

type Level = "runner" | "elsewhere" | "parse";

const LEVEL_TEXT: Readonly<Record<Level, string>> = {
  runner: "runs",
  elsewhere: "tested",
  parse: "parsed",
};

const cell = (text: string) => text.replaceAll("|", "\\|").replaceAll("\n", " ");
const code = (text: string) => (text.includes("`") ? `\`\` ${text} \`\`` : `\`${text}\``);

function label(f: { readonly feature: string; readonly value?: string }): string {
  return f.value === undefined ? code(f.feature) : `${code(f.feature)} = ${code(f.value)}`;
}

interface Proven {
  readonly level: Level | undefined;
  readonly by: string;
}

function provenBy(key: string, input: CompatibilityInput): Proven {
  const proofs: { level: Level; by: readonly string[]; why?: string }[] = [];
  for (const c of input.cases) {
    for (const proof of c.proves) {
      if (rowKey(proof) !== key) continue;
      const parseOnly = "level" in proof || !c.tiers.includes("runner");
      proofs.push({
        level: parseOnly ? "parse" : "runner",
        by: [code(c.id)],
        ...("why" in proof && { why: proof.why }),
      });
    }
  }
  for (const e of input.elsewhere)
    if (rowKey(e.ref) === key)
      proofs.push({ level: "elsewhere", by: e.tests.map(code), why: e.why });
  const level = (["runner", "elsewhere", "parse"] as const).find((l) =>
    proofs.some((p) => p.level === l),
  );
  const shown = proofs.filter((p) => p.level === level);
  const by = [...new Set(shown.flatMap((p) => p.by))].join(", ");
  const why = [...new Set(shown.flatMap((p) => (p.why ? [p.why] : [])))].join(" ");
  return { level, by: why ? `${by}. ${why}` : by };
}

function row(f: WorkflowFeature, input: CompatibilityInput): string {
  if (f.status === "unsupported")
    return `| ${cell(label(f))} | unsupported | — | ${cell(f.reason)} |`;
  const { level, by } = provenBy(rowKey(f), input);
  if (level === undefined) return `| ${cell(label(f))} | supported | **not proven** | — |`;
  return `| ${cell(label(f))} | supported | ${LEVEL_TEXT[level]} | ${cell(by)} |`;
}

export function generate(input: CompatibilityInput = DEFAULT_INPUT): string {
  const lines: string[] = [
    "# Workflow compatibility",
    "",
    "<!-- Generated by tools/ci/src/gen-compatibility.ts from the parser's support matrix and the workflow corpus. Do not edit: UPDATE_COMPATIBILITY=1 pnpm --filter @fyrden/ci-tools test compatibility-doc rewrites it. -->",
    "",
    "Which GitHub Actions workflow features Fyrden accepts, and what shows each one works. Every key and value GitHub documents is listed; a key not listed is refused as unknown, and an unsupported one is refused with the reason below.",
    "",
    "## How each feature is shown",
    "",
    "- **runs**: a workflow in the corpus (`packages/testing/src/ci-corpus/`) runs on the pinned runners below and its outcome is checked through the REST API. The nightly workflow runs every such case on both runner versions ([runs](" +
      NIGHTLY +
      ")), and pull requests that change the corpus or the runner paths run them on the newer one.",
    "- **tested**: an existing test named in the row shows the behaviour, because it is decided by the forge before any runner is involved.",
    "- **parsed**: the parser accepts and models it, checked on every pull request; the row says why the runner tier shows no more.",
    "",
    "## Versions",
    "",
    `- gitea/runner: ${input.runnerVersions.map(code).join(", ")}, each binary pinned by SHA-256.`,
    ...input.actionPins.map((p) => `- ${code(`${p.action}@${p.commit}`)} (${p.tag})`),
    ...Object.entries(input.images).map(([role, image]) => `- ${role} image: ${code(image)}`),
    "",
  ];
  for (const { area, title } of AREAS) {
    lines.push(
      `## ${title}`,
      "",
      "| Feature | Status | Shown | By, or why not |",
      "|---|---|---|---|",
    );
    for (const f of input.features) if (f.area === area) lines.push(row(f, input));
    lines.push("");
  }
  lines.push(
    "## Known differences",
    "",
    "- **Actions stored on the forge** are not resolved yet: `owner/repo@ref` always names a repository on github.com. Use `./path` after `actions/checkout` for an action in the same repository.",
    "- **Action references** keep GitHub's grammar: `owner/repo[/path]@ref`, `./path` and `docker://image`. Absolute URLs are refused.",
    "- **`$/path`** is refused, although GitHub.com runs it as an action in the same repository at the running commit (GitHub Enterprise Server does not support it; verified in [GitHub's documentation](" +
      SAME_REPOSITORY_ACTION +
      "), 2026-11-28). Use `./path` after `actions/checkout`.",
    "- The refusal covers references written in the workflow, not references inside the composite actions it uses: the runner reads those, and accepts its own forms there.",
    "- **The Actions cache** lives on each runner, in the runner's own cache server; there is no cache shared between runners yet. The corpus checks save and restore with `actions/cache` v6.1.0 and v4.3.0 on a runner with its cache on, and that a restore with the cache off restores nothing and does not fail (measured with both pinned runner versions, 2026-11-28). Operators turn the cache off on runners that take public or fork jobs (`docs/ci/runners.md`).",
    "- **Artifacts** are not served yet: nothing in the forge answers `actions/upload-artifact` or `actions/download-artifact`.",
    "",
  );
  return lines.join("\n");
}
